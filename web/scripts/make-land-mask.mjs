// One-off generator for lib/landMask.ts: a 1-degree land/sea bitmap used by the
// dotted globe, so the hero needs no texture download.
//   npm i --no-save world-atlas topojson-client d3-geo
//   node scripts/make-land-mask.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const topo = JSON.parse(
  readFileSync(new URL("../node_modules/world-atlas/land-110m.json", import.meta.url)),
);
const land = feature(topo, topo.objects.land);

const W = 360;
const H = 180;
const bytes = new Uint8Array((W * H) / 8);
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5);
  for (let x = 0; x < W; x++) {
    const lon = -180 + (x + 0.5);
    if (geoContains(land, [lon, lat])) {
      const i = y * W + x;
      bytes[i >> 3] |= 1 << (i & 7);
    }
  }
}

const b64 = Buffer.from(bytes).toString("base64");
writeFileSync(
  new URL("../lib/landMask.ts", import.meta.url),
  `// Generated by scripts/make-land-mask.mjs (Natural Earth 110m land, public domain).
// 360x180 bitmap, row 0 = 90N, col 0 = 180W, bit i = row*360+col (LSB first).
export const LAND_W = ${W};
export const LAND_H = ${H};
export const LAND_B64 =
  "${b64}";
`,
);
console.log("bytes", bytes.length, "b64", b64.length);
